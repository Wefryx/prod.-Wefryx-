create table if not exists public.portfolio (
  id bigint generated by default as identity primary key,
  title text not null,
  duration text default '',
  category text not null check (category in ('short','long')),
  video_path text not null,
  video_url text not null,
  published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
alter table public.portfolio enable row level security;
drop policy if exists "public can read published portfolio" on public.portfolio;
create policy "public can read published portfolio" on public.portfolio for select using (published = true);


-- Администраторы. После создания пользователя в Authentication -> Users
-- добавь его UUID в эту таблицу. Только эти UUID получают права модерации.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;
drop policy if exists "admins can read own admin record" on public.admin_users;
create policy "admins can read own admin record" on public.admin_users for select to authenticated using (user_id = auth.uid());

create or replace function public.is_wefryx_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(select 1 from public.admin_users where user_id = auth.uid());
$$;

-- Портфолио: публично только опубликованное; изменение только администраторам.
drop policy if exists "authenticated can insert portfolio" on public.portfolio;
create policy "admins can insert portfolio" on public.portfolio for insert to authenticated with check (public.is_wefryx_admin());
drop policy if exists "authenticated can delete portfolio" on public.portfolio;
create policy "admins can delete portfolio" on public.portfolio for delete to authenticated using (public.is_wefryx_admin());
drop policy if exists "admins can update portfolio" on public.portfolio;
create policy "admins can update portfolio" on public.portfolio for update to authenticated using (public.is_wefryx_admin()) with check (public.is_wefryx_admin());

