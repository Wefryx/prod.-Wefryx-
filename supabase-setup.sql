create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(trim(nickname)) between 2 and 40),
  service_type text not null check (service_type in ('reels','long_video','commercial','motion')),
  rating integer not null check (rating between 1 and 5),
  review_text text not null check (char_length(trim(review_text)) between 5 and 1000),
  approved boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.reviews enable row level security;
-- Любой посетитель видит только одобренные отзывы.
drop policy if exists "public can read approved reviews" on public.reviews;
create policy "public can read approved reviews" on public.reviews for select using (approved = true);
-- Посетитель может только отправить новый отзыв и не может сразу его опубликовать.
drop policy if exists "public can submit reviews" on public.reviews;
create policy "public can submit reviews" on public.reviews for insert to anon, authenticated with check (approved = false);
-- Только админ может менять статус/удалять отзывы.
drop policy if exists "authenticated can manage reviews" on public.reviews;
create policy "admins can manage reviews" on public.reviews for update to authenticated using (public.is_wefryx_admin()) with check (public.is_wefryx_admin());
drop policy if exists "authenticated can delete reviews" on public.reviews;
create policy "admins can delete reviews" on public.reviews for delete to authenticated using (public.is_wefryx_admin());

